/**
 * Разговоры жителей (systems/Talk.ts). Не одни и те же фразы по кругу, а беседа по делу:
 *  — слухи: о происшествиях знают свидетели (и родня пострадавшего), рассказывают другим — слух расходится;
 *    кто уже знал — отвечает «слышал», впервые слышит — по своему отношению;
 *  — темы по обстановке: голод, раздача, код тревоги, ночь, утро, бой на КПП, стража рядом, работа, безработица,
 *    деньги, родня (что с ней на самом деле: в КПЗ, в розыске, курсант, на смене, погибла), спор лоялиста с
 *    недовольным, район банды;
 *  — у ВС на посту — вызовы по рации (чем кончились), потери, нехватка людей, смена; в лагере — наступление,
 *    погибшие, свои в тюрьме; у курсантов — экзамен, тир; у банды — общак, соперники, барыга.
 * Ответ зависит от отношения собеседника (Attitude): лоялист, обычный, недовольный, «блатной» (банды, воры),
 * силовик, повстанец. Память: свои недавние фразы и темы, общие недавние фразы — без повторов.
 *
 * Подстановки: {bname}/{aname} — имя собеседника/говорящего, {where} — «на Заводской улице», {ago} — «только что»,
 * {who} — о ком слух, {what} — что случилось, {gang}/{rival} — банды, {front} — КПП, {kin} — родственник, {job} —
 * работа, {n} — число, {units} — кто ездил.
 */
export type Attitude = 'loyal' | 'neutral' | 'grumble' | 'tough' | 'cp' | 'rebel';
export type ByAtt = Partial<Record<Attitude | 'any', readonly string[]>>;

/**
 * Тема разговора: A начинает, B отвечает, A реагирует (back — по отношению A, backTo — на ответ B, по
 * отношению B), B подводит итог (end). variants — варианты «вопрос — подходящие ответы» (ответ к своему вопросу).
 */
export interface TopicLines {
  open: ByAtt;
  reply: ByAtt;
  back?: ByAtt;
  backTo?: ByAtt;
  end?: ByAtt;
}
export interface TopicDef extends TopicLines {
  w: number;
  variants?: readonly TopicLines[];
}

/** Слух: A рассказывает, B уже знал (knew) или слышит впервые (reply), A подхватывает; один — remark. */
export interface NewsDef {
  open: ByAtt;
  knew: ByAtt;
  reply: ByAtt;
  back?: ByAtt;
  remark: readonly string[];
}

