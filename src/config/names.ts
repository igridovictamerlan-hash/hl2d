/** Фамилии с женской формой: «-ов/-ев/-ин» → «-ова/-ева/-ина». */
export function genderedLastName(last: string, female: boolean): string {
  if (!female) return last;
  if (/(ов|ев|ин)$/.test(last)) return last + 'а';
  if (/ски$/.test(last)) return last.slice(0, -1) + 'а';
  return last;
}

