/**
 * Оружие в руках — вид сверху. Координаты в px мира в системе персонажа: x — вперёд (куда смотрит),
 * y — вправо; начало — центр кружка (радиус 12). Детали рисуются по порядку:
 *   r — прямоугольник [x0, y0, x1, y1], p — многоугольник, l — ломаная (w — толщина), o — круг [x, y, r];
 *   glow — светится (ядро AR2, кончик дубинки, болт арбалета).
 * hold — как держат: long — у плеча двумя руками; pistol — от бедра одной рукой, в прицеле двумя
 * перед собой; melee — в правой руке. hands — где кисти (в тех же координатах, до сдвига позы).
 * muzzle — дульный срез (x): оттуда трассер и вспышка.
 */
export type SpritePart =
  | { r: [number, number, number, number]; c: string; glow?: boolean }
  | { p: [number, number][]; c: string; glow?: boolean }
  | { l: [number, number][]; c: string; w: number; glow?: boolean }
  | { o: [number, number, number]; c: string; glow?: boolean };

export interface WeaponSprite {
  hold: 'long' | 'pistol' | 'melee';
  parts: SpritePart[];
  hands: [number, number][];
  muzzle: number;
}

