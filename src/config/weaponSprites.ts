/**
 * Оружие в стиле RimWorld: плоский силуэт сбоку с тёмным контуром, поворачивается за прицелом
 * (целится влево — отражается, чтобы не висеть вверх ногами). Координаты — px мира: x — вдоль ствола
 * (0 — рукоять, где держит), y — вниз (магазин и рукоять ниже ствола). Детали по порядку:
 *   r — прямоугольник [x0, y0, x1, y1], p — многоугольник, l — линия (w — толщина), o — круг [x, y, r];
 *   glow — светится (ядро AR2, кончик дубинки, болт арбалета).
 * muzzle — дульный срез [x, y]: оттуда трассер и вспышка.
 */
export type SpritePart =
  | { r: [number, number, number, number]; c: string; glow?: boolean }
  | { p: [number, number][]; c: string; glow?: boolean }
  | { l: [number, number][]; c: string; w: number; glow?: boolean }
  | { o: [number, number, number]; c: string; glow?: boolean };

export interface WeaponSprite {
  parts: SpritePart[];
  muzzle: [number, number];
}

