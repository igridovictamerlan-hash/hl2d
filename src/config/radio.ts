/**
 * Рация силового блока (systems/Radio.ts): происшествие → доклад заметившего юнита → вызов Надзора
 * (диспетчер) с местом и тем, кто едет → подтверждения ближайших («принял, буду через минуту») → «на месте»
 * → «контакт, нужна подмога» (Надзор шлёт ещё) или «чисто» / «задержан» / «нейтрализован» → отбой. Реплики —
 * облачком с рацией над головой юнита; Надзор слышно из рации юнитов рядом. Плановые переклички постов и
 * опрос «доложите обстановку» — ответ по тому, чем юнит на самом деле занят.
 *
 * Подстановки: {unit} — позывной говорящего (или адресата), {by} — позывной доложившего, {units} — кто едет,
 * {where} — «на Заводской улице», {zone} — имя зоны, {what} — что случилось, {suspect} — приметы, {eta} — когда
 * будет, {dir} — куда бежит, {ahead} — где перехватить, {victim} — позывной пострадавшего, {code} — код вызова,
 * {n} — номер группы или число, {front} — КПП, {point} — точка D.
 */
export type IncidentKind =
  | 'shots' | 'gunfire' | 'armed' | 'attack' | 'contact' | 'unitDown' | 'officerDown' | 'body'
  | 'sabotage' | 'escape' | 'riot' | 'gang' | 'convoy' | 'prison' | 'depot' | 'scanner' | 'tip'
  | 'fugitive' | 'brawl' | 'generic' | 'murder' | 'stabbing' | 'serial' | 'screams' | 'district';

export interface IncidentDef {
  /** Код вызова (по рации). */
  code: string;
  /** Сколько юнитов слать (0 — только доклад и «принято»). */
  units: number;
  /** Бегом (нападение на юнит, перестрелка). */
  urgent: boolean;
  /** Важность: важное перебивает плановые переговоры и не сливается с мелким. */
  prio: number;
  /** Доклад заметившего юнита. */
  report: readonly string[];
  /** Подтверждение посланного (иначе — общие ack / ackUrgent). */
  ack?: readonly string[];
  /** Вызов Надзора (к нему спереди — «Принято, {by}.», если кто-то доложил). */
  dispatch: readonly string[];
  /** Юнит прибыл (иначе — общие RADIO.lines.onScene). */
  onScene?: readonly string[];
  /** Слух для жителей (Talk): о чём будут говорить. */
  rumor: string;
}

